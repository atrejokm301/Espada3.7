export function searchInChapter(
  verses: Verse[],
  query: string,
): Verse[] {
  const q = query.trim().toLowerCase();
  if (!q) return verses;
  return verses.filter(
    (v) =>
      v.text.toLowerCase().includes(q) ||
      String(v.verse).includes(q),
  );
}
